import { hasOpenModal } from './modal-history.js';

/**
 * true لو إحنا فعليًا واقفين في تبويب "الرئيسية" (tab-home) دلوقتي -
 * بتقرا كلاس .active على عناصر .tab-content مباشرة من الـ DOM (نفس
 * الطريقة اللي app.js بيفعّل بيها التابات في switchTab()) بدل ما
 * نعتمد على تاريخ المتصفح نفسه، عشان الفحص يعكس اللي المستخدم شايفه
 * فعليًا على الشاشة بالظبط، مش أي حالة داخلية تانية
 * @returns {boolean}
 */
function isOnHomeTab() {
    const activeTab = document.querySelector('.tab-content.active');
    return !activeTab || activeTab.id === 'tab-home';
}

function initHardwareBackButton() {
    if (!window.Capacitor?.isNativePlatform?.()) return;

    const CapApp = window.Capacitor?.Plugins?.App;
    if (!CapApp?.addListener) return;

    CapApp.addListener('backButton', () => {
        // فيه مودال مفتوح (بروفايل/شات/أي نافذة فرعية) أو إحنا في تاب
        // غير "الرئيسية" - فيه فعلاً حاجة نرجعلها. history.back() هيطلق
        // popstate تلقائيًا، وده معالج صح بالفعل في modal-history.js
        // (بيقفل آخر مودال) وjs/app.js (بيرجع للتاب اللي قبله)
        if (hasOpenModal() || !isOnHomeTab()) {
            window.history.back();
            return;
        }

        // إحنا فعليًا في تبويب الرئيسية من غير أي مودال مفتوح - مفيش
        // حاجة تانية نرجعلها، فالسلوك الصح هنا هو الخروج الفعلي من التطبيق
        CapApp.exitApp();
    });
}

initHardwareBackButton();
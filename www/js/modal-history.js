/* ==================================================================
   سِكّاوي | js/modal-history.js
   ------------------------------------------------------------------
   وحدة صغيرة مشتركة (بدون أي state خاص بمودال معين) مهمتها فقط ربط
   أي مودال في التطبيق بزرار الرجوع بتاع الموبايل (Browser Back /
   Swipe Back) عن طريق History API، بحيث:

   - فتح مودال  = يضيف "خطوة" وهمية في تاريخ المتصفح (من غير ما يغيّر
     الـ URL خالص) عبر history.pushState.
   - الضغط على زرار رجوع الموبايل وفيه مودال مفتوح = يقفل المودال بس
     (عن طريق حدث popstate)، ومبيخرجش من الصفحة/الصفحة اللي قبلها.
   - قفل المودال يدويًا (زرار X، ضغط برّه المودال، انتهاء تلقائي..إلخ)
     = لازم يعدي من هنا (closeModal) بدل ما ينادي دالة الإخفاء مباشرة،
     عشان نستهلك الـ state اللي كنا ضفناها بـ history.back()، وبالتالي
     يفضل تاريخ المتصفح متزامن 100% مع اللي المستخدم شايفه على الشاشة.

   بيدعم مودالات متداخلة (Stack) - زي editAvatarCropModal اللي بيتفتح
   فوق editProfileModal: كل واحد بيتسجل بدالة إغلاقه الخاصة، وزرار
   الرجوع بيقفل "آخر" مودال اتفتح بس، مش كله مرة واحدة.
   ================================================================== */

// كل عنصر هنا = دالة إغلاق مودال حقيقية (اللي بتشيل class hidden..إلخ)
// اتسجلت وقت فتح المودال ده بالظبط
const modalStack = [];

/**
 * تُستدعى عند فتح أي مودال في التطبيق (فور ما تظهره على الشاشة).
 * بتضيف خطوة جديدة في تاريخ المتصفح وبتسجل دالة إغلاقه في الـ Stack.
 *
 * @param {Function} hideModalFn - دالة الإخفاء "الخام" بتاعة المودال
 *   ده (اللي بتشيل hidden/تضيف hidden..إلخ) - من غير ما تنادي
 *   history.back() جواها أبداً، عشان منعملش حلقة أو نستهلك خطوتين.
 */
export function pushModalState(hideModalFn) {
    modalStack.push(hideModalFn);
    history.pushState({ appModal: true, depth: modalStack.length }, '');
}

/**
 * تُستدعى من أي مكان بيقفل المودال يدويًا (زرار X، ضغط برّه المودال،
 * قفل تلقائي بعد نهاية محتوى..إلخ) بدل ما تنادي دالة الإخفاء مباشرة.
 * بتستهلك (تشيل) الـ state اللي ضفناها في pushModalState عن طريق
 * history.back()، واللي هيطلق حدث popstate تلقائيًا - وده اللي فعليًا
 * هيقفل المودال (شوف الـ listener تحت).
 *
 * لو المودال مش متسجل في الـ Stack أصلاً (نُدي احتياطي، أو الدالة
 * اتنادت مرتين غلط)، بتتجاهل الاستدعاء بهدوء عشان متكسرش تنقل تاريخ
 * المتصفح.
 */
export function closeModal() {
    if (modalStack.length === 0) return;
    history.back();
}

/**
 * حالة خاصة: مودال بيتقفل عشان يتفتح بدل منه مباشرة "عرض" تاني (زي
 * مودال البحث عن صديق اللي بيتقفل عشان تتفتح صفحة بروفايل عام، أو
 * مودال الاستوري اللي بيتقفل عشان يتفتح بروفايل صاحب الاستوري).
 *
 * ما ينفعش هنا نستخدم closeModal() (اللي بينادي history.back()) وبعدها
 * على طول pushModalState() للعرض الجديد، لأن history.back() غير
 * متزامن (Async) - هيحصل Race Condition حقيقي بين تنفيذ الرجوع وتنفيذ
 * الإضافة الجديدة، وممكن ياخد تاريخ المتصفح على حالة غلط تماماً.
 *
 * الحل: نستبدل "أعلى" حالة في الـ Stack بحالة العرض الجديد مباشرة عن
 * طريق history.replaceState (مش pushState) - يعني إجمالي عدد خطوات
 * تاريخ المتصفح مبيتغيرش، وزرار الرجوع هيرجع المستخدم للي كان قبل
 * المودال الأول بالظبط بضغطة واحدة (مش هيرجّعه للمودال الأول التاني
 * اللي اتقفل أصلاً).
 *
 * الاستخدام: نادي دالة الإخفاء "الخام" بتاعة المودال القديم بنفسك أول
 * (بدون المرور بـ closeModal)، وبعدين نادي replaceModalState بدالة
 * إخفاء العرض الجديد.
 *
 * @param {Function} hideModalFn - دالة الإخفاء الخام بتاعة العرض الجديد
 */
export function replaceModalState(hideModalFn) {
    if (modalStack.length > 0) modalStack.pop();
    modalStack.push(hideModalFn);
    history.replaceState({ appModal: true, depth: modalStack.length }, '');
}

// نقطة الالتقاط الوحيدة لزرار رجوع الموبايل (أو السحب من حافة الشاشة)
// أو أي استدعاء لـ history.back() (سواء من closeModal فوق أو من
// المتصفح نفسه) - بتقفل آخر مودال مفتوح بس وبترجع لو مفيش مودالات
// مفتوحة أصلاً (يبقى الـ popstate ده خاص بتنقل عادي في الصفحة، مش شغلنا)
window.addEventListener('popstate', () => {
    if (modalStack.length === 0) return;
    const hideModalFn = modalStack.pop();
    hideModalFn();
});